class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and draw 'Page X of Y' and header/footer."""
    def __init__(self, *args, **kwargs):
        super(NumberedCanvas, self).__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_header_footer(num_pages)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

    def draw_header_footer(self, page_count):
        self.saveState()
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(colors.HexColor("#4f46e5")) # Indigo
        # Running Top Header
        self.drawString(54, 11 * inch - 36, "DocuIntellect AI")
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b")) # Slate
        self.drawString(130, 11 * inch - 36, "|   Automated Intelligence & Synthesis Report")
        
        # Header divider line
        self.setStrokeColor(colors.HexColor("#e2e8f0"))
        self.setLineWidth(0.75)
        self.line(54, 11 * inch - 42, 8.5 * inch - 54, 11 * inch - 42)

        # Footer divider line
        self.line(54, 46, 8.5 * inch - 54, 46)

        # Running Footer
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#94a3b8"))
        self.drawString(54, 32, "Confidential — Generated by DocuIntellect AI Platform")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(8.5 * inch - 54, 32, page_str)
        self.restoreState()


class ReportService:
    @classmethod
    def generate_all_formats(cls, doc_obj, analysis_dict, report_config, output_dir):
        """
        Builds PDF, DOCX, and JSON report files based on user configuration.
        """
        os.makedirs(output_dir, exist_ok=True)
        rep_id = uuid.uuid4().hex[:12]
        base_name = f"Report_{rep_id}_{datetime.now().strftime('%Y%m%d_%H%M%S')}"

        pdf_path = os.path.join(output_dir, f"{base_name}.pdf")
        docx_path = os.path.join(output_dir, f"{base_name}.docx")
        json_path = os.path.join(output_dir, f"{base_name}.json")

        # 1. Generate JSON
        report_payload = cls._build_report_payload(doc_obj, analysis_dict, report_config)
        with open(json_path, 'w', encoding='utf-8') as f:
            json.dump(report_payload, f, indent=2, ensure_ascii=False)

        # 2. Generate PDF
        cls._generate_pdf(pdf_path, report_payload)

        # 3. Generate DOCX
        cls._generate_docx(docx_path, report_payload)

        return {
            'pdf_filename': os.path.basename(pdf_path),
            'docx_filename': os.path.basename(docx_path),
            'json_filename': os.path.basename(json_path),
            'report_payload': report_payload
        }

    @classmethod
    def _build_report_payload(cls, doc_obj, analysis, config):
        inclusions = config.get('inclusions', {})
        granularity = config.get('granularity', 'Standard (5 Sents)')
        archetype = config.get('archetype', 'Executive Brief')

        payload = {
            'metadata': {
                'report_title': config.get('report_title') or f"Analysis Report — {doc_obj.original_filename}",
                'author_name': config.get('author_name', 'DocuIntellect Analyst'),
                'organization': config.get('organization', 'DocuIntellect Intelligence Unit'),
                'report_date': config.get('report_date') or datetime.now().strftime('%B %d, %Y'),
                'source_filename': doc_obj.original_filename,
                'source_format': doc_obj.file_format,
                'source_word_count': doc_obj.word_count,
                'source_page_count': doc_obj.page_count,
                'archetype': archetype,
                'granularity': granularity
            },
            'sections': {}
        }

        # Calibration based on granularity
        if 'Brief' in granularity:
            summary_text = analysis.get('executive_summary', '')[:400] + "..."
        elif 'Detailed' in granularity:
            summary_text = (analysis.get('executive_summary', '') + "\n\n" + analysis.get('document_summary', '')).strip()
        else:
            summary_text = analysis.get('executive_summary', '')

        if inclusions.get('executive_summary', True):
            payload['sections']['executive_summary'] = {
                'title': '1. Executive Summary',
                'content': summary_text,
                'methodology': analysis.get('methodology', 'Extractive TextRank + Semantic Heuristics'),
                'confidence': f"{analysis.get('confidence_score', 95)}%"
            }

        if inclusions.get('document_overview', True):
            payload['sections']['document_overview'] = {
                'title': '2. Document Overview & Ingestion Context',
                'content': (
                    f"The ingested document '{doc_obj.original_filename}' comprises {doc_obj.word_count} words across "
                    f"{doc_obj.page_count} page(s). It was processed using DocuIntellect's high-fidelity extraction pipeline."
                )
            }

        if inclusions.get('key_findings', True):
            payload['sections']['key_findings'] = {
                'title': '3. Core Findings & Experimental Metrics',
                'findings': analysis.get('main_findings', [])
            }

        if inclusions.get('keywords', True):
            payload['sections']['keywords'] = {
                'title': '4. Prominent Keywords & Lexical Density',
                'keywords': [k['keyword'] for k in analysis.get('keywords', [])[:12]]
            }

        if inclusions.get('entities', True):
            payload['sections']['named_entities'] = {
                'title': '5. Multi-Class Named Entity Register',
                'entities': analysis.get('named_entities', {})
            }

        if inclusions.get('dates_numbers', True):
            payload['sections']['dates_and_numbers'] = {
                'title': '6. Temporal Markers & Quantitative Results',
                'items': analysis.get('dates_and_numbers', [])
            }

        if inclusions.get('methodology', True):
            payload['sections']['methodology'] = {
                'title': '7. Analytical Architecture & Methodology',
                'content': (
                    f"Processed via {analysis.get('methodology', 'Extractive TextRank + Semantic Heuristics')}. "
                    "Sentence centrality is computed over a graph similarity network using PageRank with damping factor d=0.85. "
                    "Named entity recognition utilizes contextual pattern extraction across organizational, temporal, and quantitative classes."
                )
            }

        if inclusions.get('conclusions', True):
            payload['sections']['conclusions'] = {
                'title': '8. Strategic Conclusions & Next Steps',
                'conclusions': analysis.get('conclusions', [])
            }

        if inclusions.get('qa_summary', False):
            # Optional QA exchange if passed
            payload['sections']['qa_summary'] = {
                'title': '9. Grounded Q&A Verification Audit',
                'notes': 'All answers verified against primary source text.'
            }

        if inclusions.get('limitations', True):
            payload['sections']['limitations'] = {
                'title': '10. Ingestion Parameters & Limitations',
                'content': (
                    "Extractive summaries rely on verifiable surface sentences present in the source document. "
                    "For purely visual or rasterized documents without an OCR layer, text extraction is bounded by digital stream availability."
                )
            }

        return payload

    @classmethod
    def _generate_pdf(cls, file_path, payload):
        meta = payload['metadata']
        sections = payload['sections']

        doc = SimpleDocTemplate(
            file_path,
            pagesize=letter,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54
        )

        styles = getSampleStyleSheet()

        # Custom typography matching SaaS aesthetics
        title_style = ParagraphStyle(
            'DocTitle',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=22,
            leading=26,
            textColor=colors.HexColor('#0f172a'),
            spaceAfter=8
        )
        subtitle_style = ParagraphStyle(
            'DocSubtitle',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=11,
            leading=15,
            textColor=colors.HexColor('#475569'),
            spaceAfter=14
        )
        h1_style = ParagraphStyle(
            'SectionH1',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=13,
            leading=17,
            textColor=colors.HexColor('#1e1b4b'), # Deep Indigo
            spaceBefore=14,
            spaceAfter=6
        )
        body_style = ParagraphStyle(
            'Body',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=9.5,
            leading=14,
            textColor=colors.HexColor('#334155'),
            spaceAfter=6
        )
        callout_style = ParagraphStyle(
            'Callout',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=9.5,
            leading=14.5,
            textColor=colors.HexColor('#1e293b')
        )
        bullet_style = ParagraphStyle(
            'Bullet',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=9,
            leading=13.5,
            textColor=colors.HexColor('#334155'),
            leftIndent=12,
            spaceAfter=4
        )

        elements = []

        # Header Title
        elements.append(Paragraph(meta['report_title'], title_style))
        elements.append(Paragraph(
            f"Archetype: <b>{meta['archetype']}</b> &nbsp;|&nbsp; Granularity: <b>{meta['granularity']}</b>",
            subtitle_style
        ))

        # Metadata Summary Table
        meta_data = [
            [
                Paragraph("<b>Document Source:</b>", body_style),
                Paragraph(meta['source_filename'], body_style),
                Paragraph("<b>Author / Unit:</b>", body_style),
                Paragraph(meta['author_name'], body_style)
            ],
            [
                Paragraph("<b>Date Generated:</b>", body_style),
                Paragraph(meta['report_date'], body_style),
                Paragraph("<b>Organization:</b>", body_style),
                Paragraph(meta.get('organization') or 'N/A', body_style)
            ],
            [
                Paragraph("<b>Word Count:</b>", body_style),
                Paragraph(f"{meta['source_word_count']} words", body_style),
                Paragraph("<b>Page Count:</b>", body_style),
                Paragraph(f"{meta['source_page_count']} page(s)", body_style)
            ]
        ]
        meta_table = Table(meta_data, colWidths=[100, 150, 100, 154])
        meta_table.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#f8fafc')),
            ('BOX', (0,0), (-1,-1), 1, colors.HexColor('#e2e8f0')),
            ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor('#f1f5f9')),
            ('TOPPADDING', (0,0), (-1,-1), 5),
            ('BOTTOMPADDING', (0,0), (-1,-1), 5),
            ('LEFTPADDING', (0,0), (-1,-1), 8),
            ('RIGHTPADDING', (0,0), (-1,-1), 8),
        ]))
        elements.append(meta_table)
        elements.append(Spacer(1, 14))

        # Render Inclusions
        if 'executive_summary' in sections:
            sec = sections['executive_summary']
            elements.append(Paragraph(sec['title'], h1_style))
            # Callout card
            summary_p = Paragraph(sec['content'], callout_style)
            conf_p = Paragraph(f"<b>Methodology:</b> {sec['methodology']} &nbsp;|&nbsp; <b>Confidence:</b> {sec['confidence']}", bullet_style)
            callout_table = Table([[summary_p], [conf_p]], colWidths=[504])
            callout_table.setStyle(TableStyle([
                ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#f0fdf4')), # Subtle mint
                ('BOX', (0,0), (-1,-1), 1, colors.HexColor('#86efac')),
                ('TOPPADDING', (0,0), (-1,-1), 8),
                ('BOTTOMPADDING', (0,0), (-1,-1), 8),
                ('LEFTPADDING', (0,0), (-1,-1), 10),
                ('RIGHTPADDING', (0,0), (-1,-1), 10),
            ]))
            elements.append(callout_table)
            elements.append(Spacer(1, 10))

        if 'document_overview' in sections:
            sec = sections['document_overview']
            elements.append(Paragraph(sec['title'], h1_style))
            elements.append(Paragraph(sec['content'], body_style))
            elements.append(Spacer(1, 8))

        if 'key_findings' in sections:
            sec = sections['key_findings']
            elements.append(Paragraph(sec['title'], h1_style))
            for f in sec['findings']:
                elements.append(Paragraph(f"• &nbsp; {f}", bullet_style))
            elements.append(Spacer(1, 8))

        if 'named_entities' in sections:
            sec = sections['named_entities']
            elements.append(Paragraph(sec['title'], h1_style))
            ent_rows = [
                [Paragraph("<b>Entity Classification</b>", body_style), Paragraph("<b>Extracted Instances</b>", body_style)]
            ]
            ent_dict = sec['entities']
            for cat, items in ent_dict.items():
                if items:
                    cat_name = cat.replace('_', ' ').title()
                    vals = ", ".join([i['value'] for i in items[:8]])
                    ent_rows.append([Paragraph(cat_name, body_style), Paragraph(vals, body_style)])
            
            if len(ent_rows) > 1:
                ent_table = Table(ent_rows, colWidths=[150, 354])
                ent_table.setStyle(TableStyle([
                    ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#e0e7ff')),
                    ('BOX', (0,0), (-1,-1), 1, colors.HexColor('#c7d2fe')),
                    ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor('#e0e7ff')),
                    ('TOPPADDING', (0,0), (-1,-1), 4),
                    ('BOTTOMPADDING', (0,0), (-1,-1), 4),
                    ('LEFTPADDING', (0,0), (-1,-1), 6),
                    ('RIGHTPADDING', (0,0), (-1,-1), 6),
                ]))
                elements.append(ent_table)
                elements.append(Spacer(1, 10))

        if 'dates_and_numbers' in sections:
            sec = sections['dates_and_numbers']
            elements.append(Paragraph(sec['title'], h1_style))
            items_str = ", ".join([f"{item['value']} ({item['category']})" for item in sec['items'][:10]])
            elements.append(Paragraph(items_str or "No explicit numerical entries isolated.", body_style))
            elements.append(Spacer(1, 8))

        if 'keywords' in sections:
            sec = sections['keywords']
            elements.append(Paragraph(sec['title'], h1_style))
            kw_str = " &nbsp;•&nbsp; ".join(sec['keywords'])
            elements.append(Paragraph(f"<b>Key Concepts:</b> {kw_str}", body_style))
            elements.append(Spacer(1, 8))

        if 'methodology' in sections:
            sec = sections['methodology']
            elements.append(Paragraph(sec['title'], h1_style))
            elements.append(Paragraph(sec['content'], body_style))
            elements.append(Spacer(1, 8))

        if 'conclusions' in sections:
            sec = sections['conclusions']
            elements.append(Paragraph(sec['title'], h1_style))
            for c in sec['conclusions']:
                elements.append(Paragraph(f"• &nbsp; {c}", bullet_style))
            elements.append(Spacer(1, 8))

        if 'limitations' in sections:
            sec = sections['limitations']
            elements.append(Paragraph(sec['title'], h1_style))
            elements.append(Paragraph(sec['content'], body_style))

        doc.build(elements, canvasmaker=NumberedCanvas)

    @classmethod
    def _generate_docx(cls, file_path, payload):
        meta = payload['metadata']
        sections = payload['sections']

        doc = docx.Document()
        
        # Set standard margins (0.75 in)
        for s in doc.sections:
            s.top_margin = Inches(0.75)
            s.bottom_margin = Inches(0.75)
            s.left_margin = Inches(0.75)
            s.right_margin = Inches(0.75)

        # Title
        t = doc.add_heading(level=0)
        t_run = t.add_run(meta['report_title'])
        t_run.font.name = 'Calibri'
        t_run.font.size = Pt(22)
        t_run.font.color.rgb = RGBColor(15, 23, 42)

        # Subtitle
        sub = doc.add_paragraph()
        sub_run = sub.add_run(f"DocuIntellect AI Synthesis  |  Archetype: {meta['archetype']}  |  Granularity: {meta['granularity']}")
        sub_run.font.name = 'Calibri'
        sub_run.font.size = Pt(10)
        sub_run.font.color.rgb = RGBColor(71, 85, 105)

        # Metadata Table
        table = doc.add_table(rows=3, cols=4)
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        meta_items = [
            ("Source Document:", meta['source_filename'], "Author / Unit:", meta['author_name']),
            ("Date Generated:", meta['report_date'], "Organization:", meta.get('organization') or 'N/A'),
            ("Total Words:", f"{meta['source_word_count']} words", "Total Pages:", f"{meta['source_page_count']} page(s)")
        ]
        for row_idx, data in enumerate(meta_items):
            row = table.rows[row_idx]
            for col_idx in range(4):
                cell = row.cells[col_idx]
                cell.text = data[col_idx]
                for p in cell.paragraphs:
                    p.paragraph_format.space_after = Pt(2)
                    p.paragraph_format.space_before = Pt(2)
                    for r in p.runs:
                        r.font.name = 'Calibri'
                        r.font.size = Pt(9)
                        if col_idx in [0, 2]:
                            r.font.bold = True

        doc.add_paragraph() # Spacing

        # Render sections
        for sec_key, sec in sections.items():
            h = doc.add_heading(sec['title'], level=1)
            for r in h.runs:
                r.font.name = 'Calibri'
                r.font.size = Pt(14)
                r.font.color.rgb = RGBColor(30, 27, 75)

            if 'content' in sec:
                p = doc.add_paragraph(sec['content'])
                p.paragraph_format.line_spacing = 1.15
            if 'findings' in sec:
                for f in sec['findings']:
                    doc.add_paragraph(f, style='List Bullet')
            if 'conclusions' in sec:
                for c in sec['conclusions']:
                    doc.add_paragraph(c, style='List Bullet')
            if 'keywords' in sec:
                doc.add_paragraph(", ".join(sec['keywords']))
            if 'entities' in sec:
                ent_table = doc.add_table(rows=1, cols=2)
                ent_table.rows[0].cells[0].text = "Category"
                ent_table.rows[0].cells[1].text = "Identified Entities"
                for cat, items in sec['entities'].items():
                    if items:
                        row = ent_table.add_row()
                        row.cells[0].text = cat.replace('_', ' ').title()
                        row.cells[1].text = ", ".join([i['value'] for i in items[:8]])
            if 'items' in sec:
                doc.add_paragraph(", ".join([f"{i['value']} ({i['category']})" for i in sec['items'][:10]]))

        doc.save(file_path)
